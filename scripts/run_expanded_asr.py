"""Prepare duration-verified existing corpora, then run five-epoch Large-v3 LoRA.

All model stages run sequentially. Existing official test audio never supplies
training labels. Outputs, checkpoints and machine-specific snapshots stay local.
"""
import argparse
import json
import math
from pathlib import Path
import shutil
import subprocess
import sys
import tarfile
from time import time_ns

from voice_to_soap.asr_component import file_sha256
from voice_to_soap.asr_comparison import load_run
from voice_to_soap.asr_training_data import read_segments, check_disjoint
from voice_to_soap.audio import _resolve_asr_device
from voice_to_soap.config import load_config
from voice_to_soap.datasets import load_manifest
from voice_to_soap.io_utils import write_json
from run_asr_lora_experiment import combine

ROOT = Path(__file__).resolve().parents[1]


def complete(directory):
    path = Path(directory) / "preparation.json"
    return path.exists() and json.loads(path.read_text())["status"] == "complete"


def run(args):
    root = Path(args.outdir).resolve()
    root.mkdir(parents=True, exist_ok=args.resume)
    device = _resolve_asr_device(args.device)
    config = load_config(args.config)
    if config["training"]["epochs"] != 5 or config["training"]["early_stopping_patience"] < 5:
        raise ValueError("This experiment requires five complete epochs unless execution fails")
    settings = {"config_sha256": file_sha256(Path(args.config)), "english_seconds": args.english_hours * 3600,
        "indic_seconds": args.indic_hours * 3600, "validation_per_language": args.validation_per_language,
        "existing_clinical_train": args.existing_clinical_train, "clinical_validation": args.clinical_validation,
        "baseline_run": args.baseline_run, "device": device}
    if any(not math.isfinite(value) or value <= 0 for value in (settings["english_seconds"], settings["indic_seconds"])):
        raise ValueError("Positive training durations are required")
    state_file = root / "expanded-run.json"
    if args.resume and state_file.exists():
        previous = json.loads(state_file.read_text())
        if previous["settings"] != settings:
            raise ValueError("Expanded-run settings changed; preserve this run and choose a new directory")
        write_json(root / f"history-before-resume-{time_ns()}.json", previous)
    state = {"status": "running", "stage": "preflight", "settings": settings,
        "limitations": ["BeTraC is synthetic English; FLEURS Hindi/Marathi is general read speech.",
            "Reference transcripts are supplied by datasets, not pseudo-labels generated by Whisper.",
            "More training is an experiment, not a guarantee of lower held-out WER/CER."]}

    def command(stage, arguments, launcher=True):
        state["stage"] = stage
        write_json(state_file, state)
        print(f"\nExpanded ASR stage: {stage}", flush=True)
        executable = [sys.executable, str(ROOT / "scripts/project.py")] if launcher else [sys.executable]
        subprocess.run([*executable, *map(str, arguments)], cwd=ROOT, check=True)

    def snapshot():
        destination = root / "reproducibility" / str(time_ns())
        destination.mkdir(parents=True)
        files = [Path(args.config), *Path("src/voice_to_soap").glob("asr*.py"),
            Path("src/voice_to_soap/whisper_lora.py"), Path("src/voice_to_soap/whisper_asr.py"),
            Path("scripts/run_expanded_asr.py"), Path("scripts/prepare_fleurs_asr.py"),
            Path("scripts/run_asr_lora_experiment.py"), Path("requirements-asr-training.txt")]
        hashes = {}
        for path in files:
            try:
                relative = path.resolve().relative_to(ROOT)
            except ValueError:
                relative = Path("external-config") / path.name
            target = destination / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, target)
            hashes[str(path)] = file_sha256(path)
        write_json(destination / "sha256.json", hashes)
        (destination / "dependencies.txt").write_bytes(subprocess.check_output([sys.executable, "-m", "pip", "freeze"]))

    try:
        snapshot()
        tests = args.fleurs_test
        if not complete(tests):
            raise ValueError("Prepare the separate held-out FLEURS test manifest before this run")
        cases = [("eka", "data/manifests/eka-smoke.csv", None),
            ("betrac", "data/processed/betrac-smoke/audio_manifest.csv", "data/outputs/vad-component-01"),
            ("sully", "data/manifests/sully-asr-selection.csv", None),
            ("fleurs", str(Path(tests) / "test_manifest.csv"), None)]
        for name, manifest, vad in cases:
            if not Path(manifest).is_file():
                raise ValueError(f"Missing existing ASR evaluation manifest: {manifest}")
            inputs = load_manifest(manifest)
            if any(not Path(row["audio_path"]).is_file() for row in inputs):
                raise ValueError(f"Missing evaluation audio for {name}")
            if vad and any(not (Path(vad) / row["encounter_id"] / "speech_segments.json").is_file() for row in inputs):
                raise ValueError(f"Prepare complete VAD artifacts before training: {vad}")
            if args.baseline_run:
                baseline = root / (name + "-base")
                source = Path(args.baseline_run) / (name + "-base")
                load_run(source)
                if not baseline.exists():
                    shutil.copytree(source, baseline)
                options = ["asr-run", "--manifest", manifest, "--outdir", baseline,
                           "--device", device, "--resume"]
                if vad:
                    options += ["--vad-dir", vad]
                command("verify_reused_" + name + "_control", options)
        prepared = root / "prepared"
        prepared.mkdir(exist_ok=True)
        validation = Path(args.clinical_validation)
        if not complete(validation):
            raise ValueError("Prepare the independent BeTraC dev validation cohort first")
        validation_rows = read_segments(validation / "segments.jsonl")
        protected_groups = {row["group_id"] for row in validation_rows}
        # Protect every BeTraC dev group, including the diagnostic test encounters.
        with tarfile.open("data/raw/betrac/data/dev-00000.tar") as archive:
            for member in archive.getmembers():
                if member.name.endswith(".json"):
                    metadata = json.load(archive.extractfile(member))
                    protected_groups.add(str(metadata.get("parentId") or metadata.get("id") or member.name[:-5]))
        existing = []
        if args.existing_clinical_train:
            old = Path(args.existing_clinical_train)
            if not complete(old):
                raise ValueError("Existing clinical preparation must be complete")
            old_rows = read_segments(old / "segments.jsonl")
            if any(row["group_id"] in protected_groups for row in old_rows):
                raise ValueError("Existing training overlaps a protected BeTraC dev group")
            existing.append(old / "segments.jsonl")
        else:
            old_rows = []
        old_seconds = sum(row["end"] - row["start"] for row in old_rows)
        exclude = {row["encounter_id"] for row in old_rows}
        with tarfile.open("data/raw/betrac-train/data/train-00000.tar") as archive:
            for member in archive.getmembers():
                if member.name.endswith(".json"):
                    metadata = json.load(archive.extractfile(member))
                    group = str(metadata.get("parentId") or metadata.get("id") or member.name[:-5])
                    if group in protected_groups:
                        exclude.add(member.name[:-5])
        fleurs = prepared / "fleurs"
        if not complete(fleurs):
            if fleurs.exists():
                raise ValueError("Partial FLEURS preparation retained; choose a fresh run directory before retrying")
            command("prepare_duration_targeted_fleurs", ["prepare-fleurs", "--outdir", fleurs,
                "--train-seconds-per-language", settings["indic_seconds"],
                "--validation-per-language", args.validation_per_language, "--seed", "42"])
        extra = prepared / "clinical-extra"
        remaining = settings["english_seconds"] - old_seconds
        if remaining > 0:
            if not complete(extra):
                options = ["asr-align", "--archive", "data/raw/betrac-train/data/train-00000.tar",
                    "--outdir", extra, "--split", "train", "--selection-seed", "45",
                    "--min-accepted-seconds", remaining]
                for uid in sorted(exclude):
                    options += ["--exclude-encounter", uid]
                if (extra / "preparation.json").exists():
                    options.append("--resume")
                command("align_additional_english_until_target", options)
            existing.append(extra / "segments.jsonl")
        clinical = prepared / "clinical-train"
        combine(existing, clinical / "segments.jsonl", resume=args.resume)
        write_json(clinical / "preparation.json", {"status": "complete", "parents": [str(path) for path in existing]})
        train = read_segments(clinical / "segments.jsonl") + read_segments(fleurs / "train.jsonl")
        valid = validation_rows + read_segments(fleurs / "validation.jsonl")
        audit = check_disjoint(train, valid)
        heldout = read_segments(Path(tests) / "test.jsonl")
        for key in ("id", "encounter_id", "group_id", "source_sha256"):
            if {row[key] for row in train + valid} & {row[key] for row in heldout}:
                raise ValueError(f"Held-out data overlap in {key}")
        durations = {lang: {"segments": sum(row["language"] == lang for row in train),
            "seconds": sum(row["end"] - row["start"] for row in train if row["language"] == lang)}
            for lang in ("en", "hi", "mr")}
        for lang, minimum in (("en", settings["english_seconds"]), ("hi", settings["indic_seconds"]), ("mr", settings["indic_seconds"])):
            if durations[lang]["seconds"] < minimum:
                raise ValueError(f"Accepted {lang} training audio falls below the requested duration")
        state.update(audit=audit, training_by_language=durations)
        write_json(root / "duration-audit.json", {"audit": audit, "training_by_language": durations})
        print(json.dumps(durations, indent=2), flush=True)
        shared = ["asr-experiment", "--clinical-train", clinical, "--clinical-validation", validation,
            "--fleurs", fleurs, "--fleurs-test", tests, "--outdir", root, "--config", args.config,
            "--device", device, "--resume", "--rerun-base"]
        command("audit_combined_manifests", [*shared, "--prepare-only"])
        if args.prepare_only:
            state.update(status="data_ready", stage="data_ready")
            return
        probe = root / "resource-probe"
        if not (probe / "run.json").exists() or json.loads((probe / "run.json").read_text())["status"] != "resource_probe_passed":
            if probe.exists():
                probe = root / f"resource-probe-retry-{time_ns()}"
            command("probe_largest_new_targets", ["asr-train", "--config", args.config,
                "--train", root / "data/train.jsonl", "--validation", root / "data/validation.jsonl",
                "--outdir", probe, "--device", device, "--probe"])
        if args.resume_source_patch:
            shared += ["--resume-source-patch", args.resume_source_patch]
        command("five_epoch_training_and_paired_evaluation", shared)
        command("compile_measured_results", ["scripts/report_asr_lora_experiment.py", "--run-dir", root], launcher=False)
        state.update(status="complete", stage="complete")
    except Exception as error:
        state.update(status="failed", error_type=type(error).__name__, error=str(error))
        raise
    finally:
        write_json(state_file, state)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--outdir", required=True)
    parser.add_argument("--config", default="configs/asr-lora-expanded.yaml")
    parser.add_argument("--device", default="auto")
    parser.add_argument("--english-hours", type=float, default=2)
    parser.add_argument("--indic-hours", type=float, default=1)
    parser.add_argument("--validation-per-language", type=int, default=32)
    parser.add_argument("--existing-clinical-train")
    parser.add_argument("--clinical-validation", default="data/processed/asr-lora-clinical-validation-run1")
    parser.add_argument("--fleurs-test", default="data/processed/asr-lora-fleurs-test-run1")
    parser.add_argument("--baseline-run", help="Optional complete matching controls; preflight-verified before training")
    parser.add_argument("--resume", action="store_true")
    parser.add_argument("--resume-source-patch")
    parser.add_argument("--prepare-only", action="store_true", help="Includes real alignment, but skips Whisper training")
    run(parser.parse_args())
